def poll(
    fn: Callable[[], Any],
    *,
    timeout_s: float = 300.0,
    interval_s: float = 5.0,
    what: str = "條件",
) -> Any:
    """輪詢直到 fn() 回傳 truthy 或逾時；逾時 raise（附上最後一個錯誤）。

    過渡期的例外（讀取視圖還沒發佈、index 世代還在切換…）會被容忍並重試；
    逾時時把最後一個錯誤一起拋出來，訊息不會被吞掉。
    """
    deadline = time.time() + timeout_s
    last: Any = None
    last_error: BaseException | None = None
    while time.time() < deadline:
        try:
            last = fn()
            last_error = None
        except Exception as e:  # noqa: BLE001 - 過渡期的讀取錯誤：重試到逾時
            last = None
            last_error = e
        if last:
            return last
        time.sleep(interval_s)
    if last_error is not None:
        raise TimeoutError(
            f"等待逾時（{what}，{timeout_s}s）；最後的錯誤："
            f"{type(last_error).__name__}: {last_error}"
        ) from last_error
    raise TimeoutError(f"等待逾時（{what}，{timeout_s}s）；最後結果：{last!r}")


def session_snapshot(reader: AgoraReader, session_id: str) -> Any:
    """讀單一 Session 的最新視圖；不存在時回 None。"""
    try:
        return reader.get_session(session_id).value
    except KeyError:
        return None


def wait_session_sha(
    reader: AgoraReader,
    session_id: str,
    raw_sha256: str | None,
    *,
    timeout_s: float = 300.0,
) -> Any:
    """等到 Agora 的讀取視圖看到這個 Session（可指定特定快照雜湊）。"""
    def _check() -> Any:
        view = session_snapshot(reader, session_id)
        if view is None:
            return None
        if raw_sha256 is None or view.session.raw_sha256.lower() == raw_sha256.lower():
            return view
        return None

    return poll(
        _check,
        timeout_s=timeout_s,
        what=f"讀取視圖看到 {session_id}"
        + (f"@{raw_sha256[:12]}" if raw_sha256 else ""),
    )


def latest_raw_sha(container: ResidentContainerHandle, session_id: str) -> str:
    """目前容器裡這個 Session 匯出的內容雜湊（用來確認同步器已上傳新版）。"""
    import hashlib

    res = container.exec_in(["opencode", "export", session_id], timeout_s=180.0)
    return hashlib.sha256(res.stdout.encode("utf-8")).hexdigest().lower()


def read_rejection_rows(reader: AgoraReader) -> list[dict[str, Any]]:
    """讀取視圖裡的全部拒收紀錄（只有代碼，沒有內容）。"""
    db = reader._client.index()
    try:
        columns = [r[1] for r in db.execute("PRAGMA table_info(rejections)")]
        if not columns:
            return []
        cur = db.execute(f"SELECT {', '.join(columns)} FROM rejections")
        return [dict(zip(columns, row)) for row in cur.fetchall()]
    finally:
        db.close()


def wait_rejection(reader: AgoraReader, item_key: str) -> dict[str, Any]:
    """等到某個 item_key 的拒收紀錄出現在讀取視圖，回傳該列。"""
    def _check() -> dict[str, Any] | None:
        for row in read_rejection_rows(reader):
            if row.get("item_key") == item_key:
                return row
        return None

    return poll(_check, what=f"拒收紀錄 {item_key} 發佈")


