#: spike 的比對工具（`docs/spike/session-import.md`）。把一份 opencode 匯出檔的
#: 訊息序列重播成「送給模型的 messages 陣列」並序列化——這是「新 session 的
#: 開頭與原 session 位元組相同」這個量的**決定性來源**。
