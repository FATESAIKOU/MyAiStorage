def _report_outcome(report: Any) -> str:
    """提交流程 run report 最後一行 → 一個可統計的結果字串。

    形如 `[RunReport 01M3…] SUCCESS | counts: …` 或
    `[RunReport 01M3…] ABORTED(pins.write_pending:WriteError) | counts: …`。
    """
    out = getattr(report, "stdout", "") or ""
    for line in reversed(out.strip().splitlines()):
        m = re.search(r"\]\s+(SUCCESS|ABORTED\([^)]*\))", line)
        if m:
            return m.group(1)
    return "UNKNOWN"


class ResidentContainerHandle:
    """管理個別住民容器的生命週期與互動。

    - `prompt()` 走 opencode 的 HTTP API（E-P1）：`POST /session` 建立 Session，
      再 `POST /session/{id}/message` 送訊息並等回覆。
    - `export()` 走 `docker exec <name> opencode export <id>`（1.7a：必須明示 id）。
    - `sync_once()` 在容器內跑同步器；提交流程由測試在本機執行（不觸發 GitHub）。
    """

    def __init__(
        self,
        name: str,
        port: int,
        *,
        work_dir: Path,
        secrets_root: Path,
        profile: str,
        model: str,
        log_path: Path,
        inbox_folder_id: str = "",
    ):
        self.inbox_folder_id = inbox_folder_id
        self.name = name
        self.port = port
        self.work_dir = work_dir  # run.sh 真正的 /work 來源（AISTORAGE_WORK_ROOT）
        self.secrets_root = secrets_root
        self.profile = profile
        self.model = model
        self.log_path = log_path
        self.proc: subprocess.Popen | None = None
        self._log_file: Any = None
        #: 最近一次 prompt_with_commits 期間提交流程的結果統計
        #: （`{"SUCCESS": 3, "ABORTED(pins.write_pending:WriteError)": 2}`）
        self.committer_tally: dict[str, int] = {}

    @property
    def api_url(self) -> str:
        return f"http://127.0.0.1:{self.port}"

    # ── HTTP API（E-P1）──────────────────────────────────────────────────

    def _request(
        self, path: str, *, method: str = "GET", payload: dict | None = None,
        timeout: float = 60.0,
    ) -> Any:
        url = f"{self.api_url}{path}?directory=/work"
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        headers = {"Accept": "application/json"}
        if data is not None:
            headers["Content-Type"] = "application/json"
        req = urllib.request.Request(url, data=data, headers=headers, method=method)
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read()
        if not body:
            return None
        return json.loads(body.decode("utf-8"))

    def wait_ready(self, timeout: float = CONTAINER_READY_TIMEOUT_S) -> None:
        """等待容器內 opencode serve 就緒。"""
        deadline = time.time() + timeout
        last_error = "（尚未連上）"
        while time.time() < deadline:
            if self.proc is not None and self.proc.poll() is not None:
                raise RuntimeError(
                    f"住民容器 {self.name} 提前結束（rc={self.proc.returncode}）；"
                    f"log: {self.log_path}"
                )
            try:
                self._request("/session", timeout=5.0)
                return
            except Exception as e:  # noqa: BLE001 - 啟動期間任何錯誤都只代表還沒好
                last_error = f"{type(e).__name__}: {e}"
                time.sleep(1.0)
        tail = ""
        try:
            tail = self.log_path.read_text(encoding="utf-8", errors="replace")[-1000:]
        except OSError:
            pass
        raise TimeoutError(
            f"住民容器 {self.name} 在 {timeout} 秒內未就緒 (port {self.port}): "
            f"{last_error}\n--- run.sh log ---\n{tail}"
        )

    def create_session(self, title: str | None = None) -> str:
        """建立一個新的主 Session，回傳 opencode 原生 id。"""
        payload: dict[str, Any] = {}
        if title:
            payload["title"] = title
        data = self._request("/session", method="POST", payload=payload)
        sid = data.get("id") if isinstance(data, dict) else None
        if not isinstance(sid, str) or not sid:
            raise RuntimeError(f"POST /session 沒有回傳 id: {data!r}")
        return sid

    def send(self, session_id: str, text: str, *, timeout_s: float = MESSAGE_TIMEOUT_S) -> dict:
        """送一則使用者訊息並等模型回覆（POST /session/{id}/message）。"""
        payload = {"parts": [{"type": "text", "text": text}]}
        data = self._request(
            f"/session/{session_id}/message", method="POST", payload=payload, timeout=timeout_s
        )
        if not isinstance(data, dict):
            raise RuntimeError(f"POST /session/{session_id}/message 回應不是物件: {data!r}")
        return data

    def prompt(
        self, text: str, *, session_id: str | None = None,
        timeout_s: float = MESSAGE_TIMEOUT_S,
    ) -> tuple[str, dict]:
        """建立（或沿用）Session 並送訊息；回傳 (session_id, 回應)。"""
        sid = session_id or self.create_session()
        return sid, self.send(sid, text, timeout_s=timeout_s)

    def prompt_with_commits(
        self,
        text: str,
        run_committer: Callable[..., Any],
        *,
        session_id: str | None = None,
        timeout_s: float = MESSAGE_TIMEOUT_S,
    ) -> tuple[str, dict]:
        """送訊息，同時在本機反覆執行提交流程（模擬 workflow 被觸發）。

        `agora_handoff`／`aistorage_split` 等工具內部會「同步 → 觸發提交 → 等讀取
        介面看得到」；e2e 不提供 PAT（不觸發 GitHub），所以由測試扮演提交流程，
        直到工具回覆為止。工具本身逾時（15 分鐘）之前必須讓它看得到。
        """
        sid = session_id or self.create_session()
        stop = threading.Event()
        errors: list[str] = []
        tally: dict[str, int] = {}

        def _loop() -> None:
            while not stop.is_set():
                try:
                    report = run_committer()
                    errors.clear()
                    # 這一輪已由 run_committer 記進全域統計
                    tally[_report_outcome(report)] = tally.get(_report_outcome(report), 0) + 1
                except Exception as e:  # noqa: BLE001 - 記錄後繼續重試
                    errors.append(str(e))
                stop.wait(COMMITTER_POLL_INTERVAL_S)

        thread = threading.Thread(target=_loop, name=f"committer-{self.name}", daemon=True)
        thread.start()
        try:
            response = self.send(sid, text, timeout_s=timeout_s)
        finally:
            stop.set()
            thread.join(timeout=60.0)
        # 提交流程每一輪的結果都留下來：A 線目前有兩種會中止的情況
        # （verify_after_push 的 MismatchError、write_pending 的 WriteError），
        # 測試要能回答「這一輪中止了幾次」而不是只看最後有沒有成功。
        self.committer_tally = dict(tally)
        print(f"[e2e:{self.name}] 提交流程 {tally or '（沒有跑成）'}"
              + (f" 例外：{errors[-1][:160]}" if errors else ""))
        return sid, response

    def revert(self, session_id: str, message_id: str) -> None:
        """撤銷到某則訊息（1.7c：`POST /session/{id}/revert`，等效 /undo）。"""
        self._request(
            f"/session/{session_id}/revert",
            method="POST",
            payload={"messageID": message_id},
            timeout=30.0,
        )

    def list_sessions(self) -> list[dict[str, Any]]:
        """取得容器內全部的 Session（含子 Session）。"""
        data = self._request("/session", timeout=15.0)
        if isinstance(data, dict):
            data = data.get("sessions") or data.get("data") or []
        if not isinstance(data, list):
            raise RuntimeError(f"GET /session 回應不是清單: {data!r}")
        return data

    def get_session(self, session_id: str) -> dict[str, Any]:
        data = self._request(f"/session/{session_id}", timeout=15.0)
        if not isinstance(data, dict):
            raise RuntimeError(f"GET /session/{session_id} 回應不是物件: {data!r}")
        return data

    # ── docker exec ──────────────────────────────────────────────────────

    def exec_in(
        self,
        args: Sequence[str],
        *,
        env: dict[str, str] | None = None,
        timeout_s: float = 300.0,
        check: bool = True,
    ) -> subprocess.CompletedProcess:
        """在容器內執行指令（除錯與測試用）。"""
        cmd = ["docker", "exec"]
        for key, value in (env or {}).items():
            cmd += ["-e", f"{key}={value}"]
        cmd += [self.name, *args]
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_s)
        if check and res.returncode != 0:
            raise RuntimeError(
                f"docker exec 失敗 (rc={res.returncode}): {' '.join(args)}\n"
                f"STDOUT: {res.stdout[-1000:]}\nSTDERR: {res.stderr[-1000:]}"
            )
        return res

    def export(self, session_id: str) -> dict[str, Any]:
        """`opencode export <id>` 的原生匯出（1.7a：必須明示 id）。

        匯出失敗要**明確說是匯出失敗**，不要讓它看起來像 AiStorage 的系統錯誤。
        9.1 e2e 實測：容器裡的對話被免費模型回覆塞到很大時，`opencode export`
        吐出被截斷的 JSON（`Unterminated string`），而呼叫端（`assert_tool_called`）
        剛好也在用匯出，於是整場 e2e 看起來像「工具被呼叫了但都失敗」——
        實際上只是匯出讀不到。
        """
        res = self.exec_in(["opencode", "export", session_id], timeout_s=180.0)
        try:
            data = json.loads(res.stdout)
        except ValueError as e:
            tail = res.stdout[-200:].replace("\n", "\\n")
            raise ExportFailed(
                f"匯出這個 Session 失敗（session={session_id}）：{e}\n"
                f"輸出長度 {len(res.stdout)} bytes，結尾是 …{tail}\n"
                "這是 opencode 匯出端的問題（常見於對話很長時輸出被截斷），"
                "不是 AiStorage 的錯誤，也無法據此判斷 AI 有沒有呼叫工具。"
            ) from None
        if not isinstance(data, dict) or "messages" not in data:
            raise ExportFailed(
                f"匯出這個 Session 失敗（session={session_id}）："
                f"形狀不符（缺 messages，拿到 {type(data).__name__}）"
            )
        return data

    def tool_parts(self, session_id: str) -> list[dict[str, Any]]:
        """匯出裡全部的 tool part 摘要（依出現順序）。"""
        out: list[dict[str, Any]] = []
        for msg in self.export(session_id).get("messages", []):
            info = msg.get("info") if isinstance(msg, dict) else None
            for part in msg.get("parts", []) if isinstance(msg, dict) else []:
                if not isinstance(part, dict) or part.get("type") != "tool":
                    continue
                state = part.get("state") if isinstance(part.get("state"), dict) else {}
                out.append(
                    {
                        "tool": part.get("tool"),
                        "call_id": part.get("callID"),
                        "message_id": info.get("id") if isinstance(info, dict) else None,
                        "status": state.get("status"),
                        "input": state.get("input"),
                        "output": state.get("output"),
                        "error": state.get("error"),
                    }
                )
        return out

