class MissingE2ESetting(RuntimeError):
    """端到端驗收測試缺少設定檔時拋出此例外（依 PM 規範：必須 FAIL，不可 skip）。"""


def _require_file(path: Path, what: str, env_override: str | None = None) -> Path:
    target = Path(os.environ[env_override]) if env_override and os.environ.get(env_override) else path
    if not target.is_file():
        raise MissingE2ESetting(
            f"E2E 驗收測試需要 {what}（路徑: {target}），但該檔不存在。"
            "請先執行 scripts/e2e_setup.py 產生端到端測試環境設定檔。"
            "（依據 PM 指示：設定缺少時必須 FAIL，不可使用 pytest.skip 掩蓋未通過驗收）。"
        )
    return target


