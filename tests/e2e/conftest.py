def assert_tool_called(
    container: ResidentContainerHandle,
    session_id: str,
    tool: str,
    *,
    count: int | None = None,
    require_ok: bool = True,
) -> list[dict[str, Any]]:
    """從 opencode 匯出確認 AI 真的呼叫了某個工具（review 的共用 helper）。

    - 找不到任何呼叫 → `ModelDidNotComply`（模型沒照做；環境問題，可換模型重跑）。
    - 有呼叫但全部失敗（state.status == "error"）→ AssertionError（系統錯誤）。
    - `count` 有給時，確認成功次數不少於 count。
    """
    parts = [p for p in container.tool_parts(session_id) if p.get("tool") == tool]
    if not parts:
        available = sorted({str(p.get("tool")) for p in container.tool_parts(session_id)})
        raise ModelDidNotComply(
            f"模型沒有呼叫工具 {tool}（session={session_id}）；"
            f"這次匯出裡看得到的工具：{available or '（一個都沒有）'}"
        )
    ok_parts = [p for p in parts if p.get("status") == "completed"]
    if require_ok and not ok_parts:
        errors = "; ".join(
            str(p.get("error") or p.get("output") or "")[:200] for p in parts
        )
        raise AssertionError(f"工具 {tool} 被呼叫了但都失敗（session={session_id}）：{errors}")
    if count is not None and len(ok_parts) < count:
        raise AssertionError(
            f"工具 {tool} 成功次數不足：預期 >= {count}，實際 {len(ok_parts)}"
        )
    return ok_parts or parts


